def get(url, binary=False):
    # curl で取る(シカゴ美術館の API は Python の標準クライアントを 403 で断る。ブラウザは装わず、この名乗りのまま)
    raw = subprocess.run(["curl", "-sS", "-f", "-L", "-m", "60", "-A", UA, url], check=True, capture_output=True).stdout
    return raw if binary else json.loads(raw.decode("utf-8"))


def jpeg_size(b):
    """JPEG の幅と高さ(SOF マーカーから)"""
    i = 2
    while i < len(b):
        if b[i] != 0xFF:
            i += 1
            continue
        m = b[i + 1]
        if m in (0xC0, 0xC1, 0xC2):
            h, w = struct.unpack(">HH", b[i + 5:i + 9])
            return w, h
        if m in (0xD8, 0x01) or 0xD0 <= m <= 0xD7:
            i += 2
            continue
        i += 2 + struct.unpack(">H", b[i + 2:i + 4])[0]
    raise ValueError("not a JPEG")


def size_cm(text):
    """'73.6 × 92.3 cm (…)' や '18 x 16 in. (45.7 x 40.6 cm)' → '73.6 × 92.3 cm'"""
    m = re.search(r"(\d+(?:\.\d+)?)\s*[x×]\s*(\d+(?:\.\d+)?)\s*cm", text or "")
    return f"{m.group(1)} × {m.group(2)} cm" if m else ""


def resolve(w):
    """→ (画像の URL, 大きさ, 美術館のページ)。パブリックドメインでなければ止める"""
    if w["src"] == "met":
        d = get(f"https://collectionapi.metmuseum.org/public/collection/v1/objects/{w['obj']}")
        assert d["isPublicDomain"] is True, f"{w['id']}: not public domain"
        return d["primaryImageSmall"], size_cm(d.get("dimensions")), f"https://www.metmuseum.org/art/collection/search/{w['obj']}"
    if w["src"] == "cma":
        d = get(f"https://openaccess-api.clevelandart.org/api/artworks/{w['obj']}")["data"]
        assert d["share_license_status"] == "CC0", f"{w['id']}: not CC0"
        return d["images"]["web"]["url"], size_cm((d.get("measurements") or "").split("Unframed:")[-1]), d.get("url") or ""
    raise ValueError(w["src"])


def build(w):
    img_url, size, page = resolve(w)
    raw = get(img_url, binary=True)
    width, height = jpeg_size(raw)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f"{w['id']}.jpg").write_bytes(raw)
    print(f"{w['id']}: {width}x{height} {len(raw) // 1024}KB size={size!r}".encode("ascii", "replace").decode())
    return {"id": w["id"], "img": f"data/art/{w['id']}.jpg", "w": width, "h": height, "title": w["title"], "artist": w["artist"], "country": w["country"], "year": w["year"],
            "medium": w["medium"], "size": size, "tech": w["tech"], "museum": MUSEUM[w["src"]], "story": w["story"], "look": w["look"], "page": page, "license": "パブリックドメイン(画像は美術館が CC0 で公開)"}


def main():
    only = set(sys.argv[1:])
    old = {x["id"]: x for x in (json.loads(INDEX.read_text(encoding="utf-8")) if INDEX.exists() else [])}
    for w in WORKS:
        if only and w["id"] not in only and not any(w["id"].startswith(o) for o in only):
            continue
        old[w["id"]] = build(w)
    INDEX.write_text(json.dumps([old[w["id"]] for w in WORKS if w["id"] in old], ensure_ascii=False, indent=1) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
