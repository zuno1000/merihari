const rich = (s) => String(s).split(/\[\[(.+?)\]\]/).map((x, i) => (i % 2 ? el('span.hp-key', x) : x));
const ico = (key) => el('span.hp-ico', svg('svg', { viewBox: '0 0 24 24', 'aria-hidden': 'true' }, svg('path', { d: ICON[key] || ICON.rec })));
const steps = (list) => el('ol.hp-steps', list.map((x, i) => el('li', [el('span.hp-num', { 'aria-hidden': 'true' }, String(i + 1)), el('div.hp-body', [el('b', x.t), el('p', rich(x.d))])])));
function tabIcon(id) {
  const src = document.querySelector(`#tabs button[data-tab="${id}"] svg`);
  return el('span.hp-tabico', src ? src.cloneNode(true) : null);
}

export function sectionHelp(rerender) {
  const go = (k) => { topic = k; rerender(); window.scrollTo(0, 0); };
  const i = TOPICS.findIndex((t) => t.key === topic);
  if (i < 0) {
    return el('div.help2', [
      el('section.card', [
        el('p.hp-title', 'メリハリの見取り図'),
        el('p.muted.small', '下の 5 つのタブと、ホーム右上の歯車(設定)でできています。'),
        el('div.hp-tabs', TABS.map((t) => el('div.hp-tab', [tabIcon(t.id), el('b', t.name), el('span', t.d)]))),
      ]),
      el('section.card', [el('p.hp-title', 'まずは この 3 つ'), steps(FIRST)]),
      el('h2.hp-h', 'テーマから探す'),
      el('div.hp-grid', TOPICS.map((t) => el('button.hp-card', { type: 'button', onclick: () => go(t.key) }, [ico(t.key), el('b', t.title), el('span', t.sub)]))),
      MORE.map ? el('details.hp-more', [el('summary', 'タブと設定の くわしい説明'), el('ul.help-ul', MORE.map.map((x) => el('li', x)))]) : null,
    ]);
  }
  const t = TOPICS[i], prev = TOPICS[i - 1], next = TOPICS[i + 1], more = MORE[t.key] || [];
  return el('div.help2', [
    el('div.row', el('button.btn.sm.ghost', { type: 'button', onclick: () => go(null) }, '‹ 使い方の一覧')),
    el('section.card', [
      el('div.hp-head', [ico(t.key), el('div', [el('p.hp-title', t.title), el('p.muted.small', `${t.sub}・${i + 1} / ${TOPICS.length}`)])]),
      steps(t.steps),
      t.tips && t.tips.length ? el('ul.hp-tips', t.tips.map((x) => el('li', rich(x)))) : null,
    ]),
    more.length ? el('details.hp-more', [el('summary', `くわしい説明(${more.length})`), el('ul.help-ul', more.map((x) => el('li', x)))]) : null,
    el('div.hp-nav', [
      prev ? el('button.btn.sm', { type: 'button', onclick: () => go(prev.key) }, `‹ ${prev.title}`) : el('span'),
      next ? el('button.btn.sm', { type: 'button', onclick: () => go(next.key) }, `${next.title} ›`) : el('span'),
    ]),
  ]);
}
